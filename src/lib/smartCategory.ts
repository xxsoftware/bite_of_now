export function autoCategorize(name: string): string {
  const normalized = name.toLowerCase().trim()

  // Direct keyword match - longer keywords first to avoid false positives
  const sortedKeywords = Object.entries(categoryKeywords).flatMap(([cat, keywords]) =>
    keywords.map((kw) => ({ category: cat, keyword: kw }))
  ).sort((a, b) => b.keyword.length - a.keyword.length)

  for (const { category, keyword } of sortedKeywords) {
    if (normalized.includes(keyword.toLowerCase())) {
      return category
    }
  }

  return '蔬菜'
}
